    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        String companyIDText = searchField.getText().trim();
        
        try {
            this.companyID = Integer.parseInt(companyIDText.replace("CMP-",""));
            
            CompanyConnector comp = new CompanyConnector();
            
            Company cmp = comp.getCompany(companyID);
            
            if(cmp != null) {
                companyNameLabel.setText(cmp.getCompanyName());
                companyContactLabel.setText(cmp.getContactNumber());
                emAddressLabel.setText(cmp.getEmailAddress());
                orderCalculation();
            }
            else {
                JOptionPane.showMessageDialog(this,"Company not found!","Not found!",JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException error) {
            JOptionPane.showMessageDialog(this,"Invalid company ID! (CMP-XXXXX)","Invalid",JOptionPane.WARNING_MESSAGE);
            return;
        }
    }//GEN-LAST:event_searchButtonActionPerformed

