    public void loadTable() {
        DefaultTableModel companyModel = (DefaultTableModel) companyTable.getModel();
        
        companyModel.setRowCount(0);
        
        CompanyConnector comp = new CompanyConnector();
        
        List<Object[]> cmp = comp.loadCompanies();
        
        for(Object[] cmps : cmp) {
            companyModel.addRow(cmps);
        }
    }
    
    private void searchOrdersTable() {

        String search = searchField.getText().trim();

        DefaultTableModel companyModel = (DefaultTableModel) companyTable.getModel();

        companyModel.setRowCount(0);
        
        CompanyConnector comp = new CompanyConnector();
        
        List<Object[]> cmp = comp.searchCompany(search);

        for (Object[] cmps : cmp) {
            companyModel.addRow(cmps);
        }
    }

