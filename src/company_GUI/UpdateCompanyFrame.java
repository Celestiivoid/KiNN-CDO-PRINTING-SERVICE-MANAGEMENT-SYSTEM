    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        String customerIDText = searchIDField.getText().trim();
        
        try {
            this.companyID = Integer.parseInt(customerIDText.replace("COMP-", ""));
            
            CustomerConnector ctmDAO = new CustomerConnector();
            
            
            CompanyConnector comp = new CompanyConnector();
            
            Company cmp = comp.getCompany(companyID);
            
            if(cmp != null) {
                companyField.setText(cmp.getCompanyName());
                contactNumberField.setText(cmp.getContactNumber());
                emailAddressField.setText(cmp.getEmailAddress());
            } else {
                JOptionPane.showMessageDialog(this,"Company not found!","Invalid search",JOptionPane.WARNING_MESSAGE);
            }
        } catch (NumberFormatException error) {
            JOptionPane.showMessageDialog(this,"Invalid customer ID (CUST-XXXXX).","Invalid ID",JOptionPane.WARNING_MESSAGE);
            return;
        }
    }//GEN-LAST:event_searchButtonActionPerformed

