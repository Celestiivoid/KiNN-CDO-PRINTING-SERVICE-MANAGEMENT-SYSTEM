    private void saveCustomerButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveCustomerButtonActionPerformed
        String companyName = companyNameField.getText();
        String contactNumber = contactNumberField.getText();
        String emailAddress = emailAddressField.getText();
        
        if(companyName.isEmpty() && contactNumber.isEmpty() && emailAddress.isEmpty()) {
            JOptionPane.showMessageDialog(this,"All fields are required to be filled out.","Warning!",JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if(companyName.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Company name field is required to be filled out.","Warning!",JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if(contactNumber.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Phone number field is required to be filled out.","Warning!",JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if(!contactNumber.matches("^0\\d{10}$")) {
            JOptionPane.showMessageDialog(this,"Phone number must start 0 and must be exactly 11 digits.","Warning",JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if(emailAddress.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Email address field is required to be filled out.","Warning!",JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        CompanyConnector cmp = new CompanyConnector();
        
        String companyID = cmp.addCompany(companyName, contactNumber, emailAddress);
        
        if(companyID != null) {
            JOptionPane.showMessageDialog(this,"Company added successfully!","Success!",JOptionPane.INFORMATION_MESSAGE);
            
            companyNameField.setText("");
            contactNumberField.setText("");
            emailAddressField.setText("");
        } else {
            JOptionPane.showMessageDialog(this,"Add company failure","Database error!",JOptionPane.ERROR_MESSAGE);
            return;
        }
    }//GEN-LAST:event_saveCustomerButtonActionPerformed

