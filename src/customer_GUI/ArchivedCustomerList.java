    private void retrieveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_retrieveButtonActionPerformed
        int selectedRow = customerTable.getSelectedRow();

        if(selectedRow == -1) {
            JOptionPane.showMessageDialog(this,"Please select a customer to retrieve.","Warning",JOptionPane.WARNING_MESSAGE);
            return;
        }

        String companyID = customerTable.getValueAt(selectedRow, 0).toString();

        int convertedCustomerID = Integer.parseInt(companyID.replace("CUST-", ""));

        String firstName = customerTable.getValueAt(selectedRow, 1).toString();

        String lastName = customerTable.getValueAt(selectedRow, 2).toString();
        
        String contactNumber = customerTable.getValueAt(selectedRow, 3).toString();
        
        String emailAddress = customerTable.getValueAt(selectedRow, 4).toString();

        int confirmation = JOptionPane.showConfirmDialog(this,"Are you sure you want to retrieve " + firstName + " " + lastName + "?","Retrieve confirmation",JOptionPane.YES_NO_OPTION,JOptionPane.WARNING_MESSAGE);

        if(confirmation == JOptionPane.YES_OPTION) {

            CustomerConnector ctm = new CustomerConnector();
            
            boolean archived = ctm.retrieveCustomer(convertedCustomerID);

            if(archived) {
                JOptionPane.showMessageDialog(this,firstName + " " + lastName + " has been retrieved successfully!","Success",JOptionPane.INFORMATION_MESSAGE);
                loadTable();
            }
            else {
                JOptionPane.showMessageDialog(this,"Error in retrieving customer.","Database error",JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
    }//GEN-LAST:event_retrieveButtonActionPerformed


