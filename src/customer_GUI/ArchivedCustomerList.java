    public void loadTable() {
        DefaultTableModel orderModel = (DefaultTableModel) customerTable.getModel();
        
        orderModel.setRowCount(0);
        
        CustomerConnector ctm = new CustomerConnector();
        
        List<Object[]> customers = ctm.loadarchivedCustomer();
        
        for(Object[] ctms : customers) {
            orderModel.addRow(ctms);
        }
    }
    
    private void searchCustomerTable() {

        String search = searchField.getText().trim();

        DefaultTableModel model = (DefaultTableModel) customerTable.getModel();

        model.setRowCount(0);

        CustomerConnector ctm = new CustomerConnector();
        
        List<Object[]> customers = ctm.searchArchivedCustomer(search);

        for (Object[] ctms : customers) {
            model.addRow(ctms);
        }
    }

